//! `--add-spoof`: per-app property overrides for a zygote preload.
//!
//! The input is one JSON array of `{"package", "props"}` entries. It is
//! validated and written as a compact `@package` / `key=value` file at
//! `system/etc/spoof/spoof.prop`, which `libspoof.so` (loaded from the JSON's
//! directory) reads once in zygote; only the matching app process applies the
//! overrides.
//!
//! Installation also puts `libspoof.so` in `system/lib64/`, adds it as the
//! first `DT_NEEDED` entry of `system/bin/app_process64` and
//! `system/bin/bootanimation`, and removes a legacy `LD_PRELOAD` line from the
//! 64-bit zygote service. The linker ignores `LD_PRELOAD` under `AT_SECURE=1`,
//! and `bootanimation` is an init-native service outside the zygote, so both
//! need the dependency to see the preload.
//!
//! ```json
//! [{"package": "com.netflix.mediaclient", "props": {"ro.product.model": "PLK110"}}]
//! ```

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use serde::Deserialize;

use crate::add_overlay::{InsertedFile, OverlayFile, insert_files};
use crate::elf_needed;
use crate::ext4_helpers::{lookup_inode_at_path, open_ext4_volume, write_via_extents};
use crate::zygote::{
    InitPatchResult, LIB_DIR, LIB_NAME, LIB_PATH, patch_init_scripts, read_existing,
    validate_elf64_aarch64,
};

pub const SPOOF_NAME: &str = "spoof.prop";
pub const SPOOF_DIR: &str = "system/etc/spoof";
pub const SPOOF_PATH: &str = "system/etc/spoof/spoof.prop";
pub const APP_PROCESS_PATH: &str = "system/bin/app_process64";

/// The boot animation runs as an init-native service, so it is not a zygote
/// child and never loads the preload through `app_process64`. It resolves the
/// hidden edition token itself to pick `bootanimation_mc.zip`.
pub const BOOTANIMATION_PATH: &str = "system/bin/bootanimation";

/// Executables that receive `libspoof.so` as their first `DT_NEEDED` entry.
/// The first entry is required; the rest are patched when the image has them.
pub const SPOOF_EXECUTABLES: &[&str] = &[APP_PROCESS_PATH, BOOTANIMATION_PATH];

const MAX_JSON_BYTES: u64 = 1024 * 1024;
const MAX_LIB_BYTES: u64 = 32 * 1024 * 1024;
const MAX_APPS: usize = 256;
const MAX_PROPS_PER_APP: usize = 512;
const MAX_PROP_KEY_BYTES: usize = 128;
const MAX_PROP_VALUE_BYTES: usize = 4096;

/// One app entry from the JSON input.
#[derive(Debug, Clone, Deserialize)]
struct SpoofEntry {
    package: String,
    props: BTreeMap<String, String>,
}

/// Validated, converted payload.
#[derive(Debug, Clone)]
pub struct SpoofPayload {
    pub config: Vec<u8>,
    pub apps: usize,
    pub props: usize,
}

/// State of one executable's `DT_NEEDED` entry after [`apply`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AppProcessPatchOutcome {
    Patched,
    AlreadyPatched,
}

impl AppProcessPatchOutcome {
    pub fn label(self) -> &'static str {
        match self {
            Self::Patched => "DT_NEEDED added",
            Self::AlreadyPatched => "DT_NEEDED already present",
        }
    }
}

/// Result of patching one loader executable.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AppProcessPatchResult {
    pub path: String,
    pub outcome: AppProcessPatchOutcome,
}

/// Result of installing the preload payload into `system.img`.
#[derive(Debug, Clone)]
pub struct SpoofApplyResult {
    pub inserted: Vec<InsertedFile>,
    pub skipped: Vec<String>,
    pub init: InitPatchResult,
    pub executables: Vec<AppProcessPatchResult>,
}

pub fn load(path: &Path) -> Result<SpoofPayload> {
    let metadata = std::fs::metadata(path)
        .with_context(|| format!("--add-spoof: reading `{}`", path.display()))?;
    if !metadata.is_file() {
        bail!("--add-spoof: `{}` is not a regular file", path.display());
    }
    if metadata.len() > MAX_JSON_BYTES {
        bail!(
            "--add-spoof: `{}` is too large ({} bytes, limit {} bytes)",
            path.display(),
            metadata.len(),
            MAX_JSON_BYTES
        );
    }
    let bytes = std::fs::read(path)
        .with_context(|| format!("--add-spoof: reading `{}`", path.display()))?;
    let mut entries: Vec<SpoofEntry> = serde_json::from_slice(&bytes).with_context(|| {
        format!(
            "--add-spoof: `{}` must be a JSON array of {{\"package\",\"props\"}} objects",
            path.display()
        )
    })?;
    if entries.is_empty() {
        bail!("--add-spoof: `{}` contains no app entries", path.display());
    }
    if entries.len() > MAX_APPS {
        bail!(
            "--add-spoof: `{}` has too many apps ({} entries, limit {MAX_APPS})",
            path.display(),
            entries.len()
        );
    }
    entries.sort_by(|a, b| a.package.cmp(&b.package));

    let mut seen = BTreeSet::new();
    let mut config = String::from("# generated by dynobox --add-spoof\n");
    let mut prop_count = 0usize;
    let mut app_count = 0usize;
    for entry in entries {
        validate_package(&entry.package, path)?;
        if !seen.insert(entry.package.clone()) {
            bail!(
                "--add-spoof: `{}` lists package `{}` more than once",
                path.display(),
                entry.package
            );
        }
        if entry.props.is_empty() {
            bail!(
                "--add-spoof: `{}` has no props for package `{}`",
                path.display(),
                entry.package
            );
        }
        if entry.props.len() > MAX_PROPS_PER_APP {
            bail!(
                "--add-spoof: `{}` has too many props for `{}` ({} entries, limit {MAX_PROPS_PER_APP})",
                path.display(),
                entry.package,
                entry.props.len()
            );
        }
        config.push('@');
        config.push_str(&entry.package);
        config.push('\n');
        for (key, value) in entry.props {
            validate_prop_key(&key, path, &entry.package)?;
            validate_prop_value(&value, path, &entry.package, &key)?;
            config.push_str(&key);
            config.push('=');
            config.push_str(&value);
            config.push('\n');
            prop_count += 1;
        }
        app_count += 1;
    }

    Ok(SpoofPayload {
        config: config.into_bytes(),
        apps: app_count,
        props: prop_count,
    })
}

/// Path of the preload library that ships next to the JSON list.
pub fn lib_path_for(json_path: &Path) -> PathBuf {
    json_path
        .parent()
        .filter(|dir| !dir.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."))
        .join(LIB_NAME)
}

/// Read and validate the arm64 preload library next to the JSON list.
pub fn load_lib(json_path: &Path) -> Result<Vec<u8>> {
    let path = lib_path_for(json_path);
    let metadata = std::fs::metadata(&path).with_context(|| {
        format!(
            "--add-spoof: reading `{}` (the preload library must sit next to the JSON list)",
            path.display()
        )
    })?;
    if !metadata.is_file() {
        bail!("--add-spoof: `{}` is not a regular file", path.display());
    }
    if metadata.len() > MAX_LIB_BYTES {
        bail!(
            "--add-spoof: `{}` is too large ({} bytes, limit {} bytes)",
            path.display(),
            metadata.len(),
            MAX_LIB_BYTES
        );
    }
    let bytes = std::fs::read(&path)
        .with_context(|| format!("--add-spoof: reading `{}`", path.display()))?;
    validate_elf64_aarch64(&bytes, &path)?;
    Ok(bytes)
}

/// Install the library, its config and the loader dependencies into
/// `system.img`.
///
/// [`SPOOF_EXECUTABLES`] receive `libspoof.so` as their first `DT_NEEDED`
/// entry. The first one is required; the others are patched when the image
/// carries them, so an image without a boot animation still installs.
///
/// Existing payload files are compared with the requested bytes; an identical
/// file is skipped so a second run against an already-patched image is a
/// no-op, while a different file is an error (rebuild from a clean input to
/// replace a payload).
pub fn apply(system_image: &Path, payload: &SpoofPayload, lib: &[u8]) -> Result<SpoofApplyResult> {
    let mut volume = open_ext4_volume(system_image)?;
    let lib_existing = read_existing(&mut volume, &["system", "lib64", LIB_NAME], "--add-spoof")?;
    let prop_existing = read_existing(
        &mut volume,
        &["system", "etc", "spoof", SPOOF_NAME],
        "--add-spoof",
    )?;
    let block_size = volume.block_size;

    let mut skipped = Vec::new();
    let mut executables = Vec::new();
    let mut patched = Vec::new();
    for (index, path) in SPOOF_EXECUTABLES.iter().enumerate() {
        let components: Vec<&str> = path.split('/').collect();
        let Some(inode) = lookup_inode_at_path(&mut volume, &components)? else {
            if index == 0 {
                bail!(
                    "--add-spoof: {APP_PROCESS_PATH} is missing; the 64-bit zygote executable is required"
                );
            }
            skipped.push(format!("{path} (not in this image)"));
            continue;
        };
        if !inode.is_file() {
            bail!("--add-spoof: {path} is not a regular file");
        }
        let (bytes, extents) = inode
            .open_read_with_extents(&mut volume)
            .with_context(|| format!("--add-spoof: reading {path}"))?;
        match elf_needed::add_needed(&bytes, LIB_NAME)
            .with_context(|| format!("--add-spoof: patching {path}"))?
        {
            Some(bytes) => {
                patched.push((path.to_string(), bytes, extents));
                executables.push(AppProcessPatchResult {
                    path: path.to_string(),
                    outcome: AppProcessPatchOutcome::Patched,
                });
            }
            None => {
                skipped.push(format!("{path} ({LIB_NAME} already present)"));
                executables.push(AppProcessPatchResult {
                    path: path.to_string(),
                    outcome: AppProcessPatchOutcome::AlreadyPatched,
                });
            }
        }
    }
    drop(volume);

    let mut inserted = Vec::new();

    if let Some(existing) = lib_existing {
        if existing != lib {
            bail!(
                "--add-spoof: {LIB_PATH} already exists with different contents; \
                 rebuild from the clean input image to replace it"
            );
        }
        skipped.push(format!("{LIB_PATH} (already present)"));
    } else {
        let files = [OverlayFile {
            name: LIB_NAME,
            bytes: lib,
        }];
        inserted.extend(
            insert_files(system_image, LIB_DIR, &files)
                .with_context(|| format!("--add-spoof: inserting {LIB_PATH}"))?,
        );
    }

    if let Some(existing) = prop_existing {
        if existing != payload.config {
            bail!(
                "--add-spoof: {SPOOF_PATH} already exists with different contents; \
                 rebuild from the clean input image to replace it"
            );
        }
        skipped.push(format!("{SPOOF_PATH} (already present)"));
    } else {
        let files = [OverlayFile {
            name: SPOOF_NAME,
            bytes: &payload.config,
        }];
        inserted.extend(
            insert_files(system_image, SPOOF_DIR, &files)
                .with_context(|| format!("--add-spoof: inserting {SPOOF_PATH}"))?,
        );
    }

    for (path, bytes, extents) in &patched {
        write_via_extents(system_image, bytes, extents, block_size)
            .with_context(|| format!("--add-spoof: writing {path}"))?;
    }

    let init = patch_init_scripts(system_image)?;
    Ok(SpoofApplyResult {
        inserted,
        skipped,
        init,
        executables,
    })
}

fn validate_package(package: &str, path: &Path) -> Result<()> {
    if package.is_empty() || package.len() > 200 {
        bail!(
            "--add-spoof: `{}` has an invalid package name (empty or longer than 200 bytes)",
            path.display()
        );
    }
    if !package.split('.').all(|segment| {
        !segment.is_empty()
            && segment
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'_')
    }) {
        bail!(
            "--add-spoof: `{}` has invalid package name `{package}`",
            path.display()
        );
    }
    Ok(())
}

fn validate_prop_key(key: &str, path: &Path, package: &str) -> Result<()> {
    if key.is_empty() || key.len() > MAX_PROP_KEY_BYTES {
        bail!(
            "--add-spoof: `{}` has an invalid prop key for `{package}` (empty or longer than {MAX_PROP_KEY_BYTES} bytes)",
            path.display()
        );
    }
    if key.starts_with('@')
        || key.starts_with('#')
        || !key
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'.' || b == b'_' || b == b'-')
    {
        bail!(
            "--add-spoof: `{}` has invalid prop key `{key}` for `{package}`",
            path.display()
        );
    }
    Ok(())
}

fn validate_prop_value(value: &str, path: &Path, package: &str, key: &str) -> Result<()> {
    if value.len() > MAX_PROP_VALUE_BYTES {
        bail!(
            "--add-spoof: `{}` value for `{package}` `{key}` is too long (limit {MAX_PROP_VALUE_BYTES} bytes)",
            path.display()
        );
    }
    if value.contains(['\n', '\r', '\0']) {
        bail!(
            "--add-spoof: `{}` value for `{package}` `{key}` contains a newline or NUL",
            path.display()
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn write_json(text: &str) -> tempfile::TempDir {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("spoof.json"), text).unwrap();
        dir
    }

    fn elf64_aarch64() -> Vec<u8> {
        let mut bytes = vec![0u8; 64];
        bytes[0..4].copy_from_slice(b"\x7fELF");
        bytes[4] = 2;
        bytes[5] = 1;
        bytes[6] = 1;
        bytes[16..18].copy_from_slice(&3u16.to_le_bytes());
        bytes[18..20].copy_from_slice(&183u16.to_le_bytes());
        bytes
    }

    #[test]
    fn converts_apps_and_sorts_keys() {
        let dir = write_json(
            r#"[

              {"package":"com.zeta.app","props":{"ro.product.model":"Z","ro.product.brand":"Zeta"}},
              {"package":"com.netflix.mediaclient","props":{"ro.product.model":"PLK110","ro.product.manufacturer":"OnePlus"}}
            ]"#,
        );
        let payload = load(&dir.path().join("spoof.json")).unwrap();
        assert_eq!(payload.apps, 2);
        assert_eq!(payload.props, 4);
        let text = String::from_utf8(payload.config).unwrap();
        let netflix = text.find("@com.netflix.mediaclient").unwrap();
        let zeta = text.find("@com.zeta.app").unwrap();
        assert!(netflix < zeta, "apps must be sorted");
        assert!(text.contains("ro.product.manufacturer=OnePlus\nro.product.model=PLK110"));
    }

    #[test]
    fn rejects_duplicate_package() {
        let dir = write_json(
            r#"[

              {"package":"com.example.app","props":{"ro.product.model":"A"}},
              {"package":"com.example.app","props":{"ro.product.model":"B"}}
            ]"#,
        );
        let err = load(&dir.path().join("spoof.json")).unwrap_err();
        assert!(err.to_string().contains("more than once"));
    }

    #[test]
    fn rejects_invalid_package() {
        let dir = write_json(r#"[{"package":"com/example","props":{"ro.product.model":"A"}}]"#);
        let err = load(&dir.path().join("spoof.json")).unwrap_err();
        assert!(err.to_string().contains("invalid package"));
    }

    #[test]
    fn rejects_invalid_prop_key() {
        let dir = write_json(r#"[{"package":"com.example.app","props":{"bad key":"A"}}]"#);
        let err = load(&dir.path().join("spoof.json")).unwrap_err();
        assert!(err.to_string().contains("invalid prop key"));
    }

    #[test]
    fn rejects_newline_in_value() {
        let dir =
            write_json(r#"[{"package":"com.example.app","props":{"ro.product.model":"A\nB"}}]"#);
        let err = load(&dir.path().join("spoof.json")).unwrap_err();
        assert!(err.to_string().contains("newline"));
    }

    #[test]
    fn rejects_empty_app_list() {
        let dir = write_json("[]");
        let err = load(&dir.path().join("spoof.json")).unwrap_err();
        assert!(err.to_string().contains("no app entries"));
    }

    #[test]
    fn load_lib_reads_the_sibling_library() {
        let dir = write_json("[]");
        std::fs::write(dir.path().join(LIB_NAME), elf64_aarch64()).unwrap();
        let lib = load_lib(&dir.path().join("spoof.json")).unwrap();
        assert_eq!(lib, elf64_aarch64());

        std::fs::remove_file(dir.path().join(LIB_NAME)).unwrap();
        let err = load_lib(&dir.path().join("spoof.json")).unwrap_err();
        assert!(err.to_string().contains(LIB_NAME));
    }

    #[test]
    fn load_lib_rejects_foreign_architectures() {
        let dir = write_json("[]");
        let mut bytes = elf64_aarch64();
        bytes[18..20].copy_from_slice(&62u16.to_le_bytes());
        std::fs::write(dir.path().join(LIB_NAME), bytes).unwrap();
        let err = load_lib(&dir.path().join("spoof.json")).unwrap_err();
        assert!(err.to_string().contains("AArch64"));
    }

    /// Real-image round trip: copies `DYNOBOX_TEST_ADD_SPOOF_IMG` (an ext4
    /// `system.img` with `system/lib64`, `system/bin/app_process64` and
    /// `init.zygote64.rc`), installs the payload, reads it back, and checks
    /// that a second run is idempotent. Ignored by default; see
    /// [`crate::test_fixtures`].
    #[test]
    #[ignore = "fixture: set DYNOBOX_TEST_ADD_SPOOF_IMG"]
    fn add_spoof_on_real_image_when_env_set() {
        let src = crate::test_fixtures::env("DYNOBOX_TEST_ADD_SPOOF_IMG");
        let work = tempfile::tempdir().unwrap();
        let image = work.path().join("system.img");
        std::fs::copy(&src, &image).expect("copy test system image");

        let payload_dir = work.path().join("spoof");
        std::fs::create_dir_all(&payload_dir).unwrap();
        let json = payload_dir.join("spoof.json");
        std::fs::write(
            &json,
            br#"[{"package":"com.example.app","props":{"ro.product.model":"X"}}]"#,
        )
        .unwrap();
        std::fs::write(payload_dir.join(LIB_NAME), elf64_aarch64()).unwrap();

        let payload = load(&json).unwrap();
        let lib = load_lib(&json).unwrap();
        let first = apply(&image, &payload, &lib).unwrap();
        assert_eq!(first.inserted.len(), 2);
        let app_process = first
            .executables
            .iter()
            .find(|entry| entry.path == APP_PROCESS_PATH)
            .expect("app_process64 entry");
        assert_eq!(app_process.outcome, AppProcessPatchOutcome::Patched);
        assert_eq!(
            first.init.outcome,
            crate::zygote::InitPatchOutcome::AlreadyClean
        );

        let mut volume = open_ext4_volume(&image).unwrap();
        let rc = crate::ext4_helpers::lookup_inode_at_path(
            &mut volume,
            &["system", "etc", "init", "hw", "init.zygote64.rc"],
        )
        .unwrap()
        .expect("init.zygote64.rc");
        let text = String::from_utf8(rc.open_read(&mut volume).unwrap()).unwrap();
        assert!(!text.contains(crate::zygote::PRELOAD_LINE));

        let app = crate::ext4_helpers::lookup_inode_at_path(
            &mut volume,
            &["system", "bin", "app_process64"],
        )
        .unwrap()
        .expect("app_process64");
        let app_bytes = app.open_read(&mut volume).unwrap();
        assert!(
            crate::elf_needed::add_needed(&app_bytes, LIB_NAME)
                .unwrap()
                .is_none()
        );

        if let Some(bootanimation) = first
            .executables
            .iter()
            .find(|entry| entry.path == BOOTANIMATION_PATH)
        {
            assert_eq!(bootanimation.outcome, AppProcessPatchOutcome::Patched);
            let binary = crate::ext4_helpers::lookup_inode_at_path(
                &mut volume,
                &["system", "bin", "bootanimation"],
            )
            .unwrap()
            .expect("bootanimation");
            let bytes = binary.open_read(&mut volume).unwrap();
            assert!(
                crate::elf_needed::add_needed(&bytes, LIB_NAME)
                    .unwrap()
                    .is_none()
            );
        }

        let second = apply(&image, &payload, &lib).unwrap();
        assert!(second.inserted.is_empty());
        assert_eq!(
            second.init.outcome,
            crate::zygote::InitPatchOutcome::AlreadyClean
        );
        assert!(
            second
                .executables
                .iter()
                .all(|entry| entry.outcome == AppProcessPatchOutcome::AlreadyPatched)
        );
    }

    #[test]
    fn loads_checked_in_netflix_payload() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../spoof/spoof.json");
        let payload = load(&path).unwrap();
        let text = String::from_utf8(payload.config).unwrap();
        assert!(text.contains("@com.netflix.mediaclient"));
        assert!(text.contains("ro.product.manufacturer=OnePlus"));
        assert!(text.contains("ro.product.model=PLK110"));
        assert!(text.contains("ro.product.name=infiniti"));
    }
}
